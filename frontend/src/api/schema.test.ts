import { expect, it } from "vitest";
import schema from "./schema.d.ts?raw";

it("generated schema has LF line endings only", () => {
  expect(schema).not.toContain("\r");
});

it("generated schema starts with the generator's do-not-edit banner", () => {
  expect(schema).toMatch(/^\/\*\*\n \* This file was auto-generated by openapi-typescript\.\n \* Do not make direct changes to the file\./);
});
