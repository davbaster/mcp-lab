// Builds the Content-Security-Policy of the frontend container from content-build/media-config.json,
// the one list of media origins. It runs in the Docker build stage and writes an nginx include file:
//
//   node scripts/csp.mjs ../content-build/media-config.json csp.conf
//
// The include holds one `add_header Content-Security-Policy "..." always;`, and nginx.conf includes it
// at server level. A config value that is not a plain https origin stops the build, so nothing in it
// (a `;`, a quote, a space, a `$`, a wildcard, a path, credentials) can reach the header. No origin is
// written in this file, in nginx.conf or anywhere else in frontend/. Dependencies: none.
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";

/** A problem with the config. The message names the key and the value. */
export class CspError extends Error {}

/**
 * A host of lowercase letters, digits, dots and hyphens, and an optional port. `new URL(...).origin`
 * alone is not enough: it also returns `https://a;b.example`, `https://a$b.example` and `https://*.example`.
 * This is the rule of `loadMediaConfig` in content-build/src/media-config.ts.
 */
const PLAIN_ORIGIN = /^https:\/\/[a-z0-9.-]+(:\d{1,5})?$/;

/** Why `value` is not an allowed origin, or undefined when it is exactly `new URL(value).origin` of an https URL. */
function originProblem(value) {
  if (typeof value !== "string") return "must be a string";
  if (!PLAIN_ORIGIN.test(value)) {
    return "must be an https origin with a host of lowercase letters, digits, dots and hyphens: no path, space, quote, semicolon, wildcard or credentials";
  }
  let origin;
  try {
    origin = new URL(value).origin;
  } catch {
    return "is not a URL";
  }
  if (origin !== value) return `must be written exactly as ${origin} (a lowercase host, no default port)`;
  return undefined;
}

/**
 * The origins in `list` (under `key` in the config), checked one by one and without repeats. For a list
 * of objects, `field` is the property that holds the origin.
 */
function origins(list, key, field) {
  if (!Array.isArray(list)) throw new CspError(`${key} must be a list`);
  const found = [];
  list.forEach((item, index) => {
    const where = field === undefined ? `${key}[${index}]` : `${key}[${index}].${field}`;
    const value = field === undefined ? item : item !== null && typeof item === "object" ? item[field] : undefined;
    const problem = originProblem(value);
    if (problem !== undefined) throw new CspError(`${where} ${problem} (got ${JSON.stringify(value)})`);
    if (!found.includes(value)) found.push(value);
  });
  return found;
}

/** The value of the header for a parsed media-config.json. */
export function buildCsp(config) {
  if (config === null || typeof config !== "object" || Array.isArray(config)) throw new CspError("the config must be an object");
  const media = origins(config.mediaOrigins, "mediaOrigins");
  const embeds = origins(config.embeds, "embeds", "origin");
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    ["img-src 'self' data: blob:", ...media].join(" "),
    ["media-src 'self'", ...media].join(" "),
    // An empty `frame-src` is not a way to block frames, so no embed means 'none'.
    ["frame-src", ...(embeds.length > 0 ? embeds : ["'none'"])].join(" "),
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

/** The nginx include file: `always` puts the header on error pages and redirects too. */
export function nginxInclude(csp) {
  // Inside nginx's double quotes these would be read as syntax (a `$` starts a variable).
  if (/["\\$\r\n]/.test(csp)) throw new CspError("the policy has a character that nginx would read as syntax");
  return [
    "# Generated by frontend/scripts/csp.mjs from content-build/media-config.json. Do not edit.",
    `add_header Content-Security-Policy "${csp}" always;`,
    "",
  ].join("\n");
}

/** The include file for the text of a media-config.json. `name` is the file's name, for messages. */
export function generate(configText, name) {
  let config;
  try {
    config = JSON.parse(configText.replace(/^\uFEFF/, ""));
  } catch (error) {
    throw new CspError(`${name}: the file is not valid JSON (${error.message})`);
  }
  try {
    return nginxInclude(buildCsp(config));
  } catch (error) {
    if (error instanceof CspError) throw new CspError(`${name}: ${error.message}`);
    throw error;
  }
}

/**
 * The command line: `<media-config.json> <output file>`. `io` is where files and messages go, so a test
 * can run it without a disk. Returns the exit code: 0, 1 for a bad or unreadable config (nothing is
 * written), 2 for the wrong arguments.
 */
export function run(args, io) {
  const [configPath, outputPath, ...extra] = args;
  if (!configPath || !outputPath || extra.length > 0) {
    io.error("Usage: node scripts/csp.mjs <media-config.json> <output file>");
    return 2;
  }
  const name = basename(configPath);
  try {
    let text;
    try {
      text = io.readFile(configPath);
    } catch {
      throw new CspError(`${name}: the file cannot be read`);
    }
    io.writeFile(outputPath, generate(text, name));
    return 0;
  } catch (error) {
    if (!(error instanceof CspError)) throw error;
    io.error(`csp: ${error.message}`);
    return 1;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = run(process.argv.slice(2), {
    readFile: (path) => readFileSync(path, "utf8"),
    writeFile: (path, text) => writeFileSync(path, text),
    error: (message) => console.error(message),
  });
}
